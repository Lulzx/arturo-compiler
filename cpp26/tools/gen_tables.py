#!/usr/bin/env python3
"""Generate cpp26/src/tables.inc from the original compiler's own tables.

Sources of truth (never hand-copied):
  src/intrinsics.art  -- generated upstream builtin declarations (395 rows)
  src/semantics.art   -- PURE_INTRINSICS / UNSUPPORTED_INTRINSICS judgements
  src/front.art       -- SHADOWABLE word list
Re-run after moving to a new pinned Arturo revision.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]


def name_set(text: str, marker: str) -> list[str]:
    i = text.index(marker)
    j = text.index("]", i)
    return sorted(set(re.findall(r'"([^"]+)": true', text[i:j])))


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    src = (ROOT / "src/intrinsics.art").read_text()
    pat = re.compile(
        r'"((?:[^"\\]|\\.)*)": #\[arity: (\d+) alias: "((?:[^"\\]|\\.)*)" '
        r'infix\?: (true|false) refs: @\[([^\]]*)\] muts: @\[([^\]]*)\]'
    )
    rows = [
        (m.group(1), int(m.group(2)), m.group(3), m.group(4) == "true", "true" in m.group(6))
        for m in pat.finditer(src)
    ]
    assert rows, "no intrinsics parsed"
    sem = (ROOT / "src/semantics.art").read_text()
    front = (ROOT / "src/front.art").read_text()
    i = front.index("SHADOWABLE:")
    shadow = sorted(set(re.findall(r"(\w+\??): true", front[i:front.index("]", i)])))

    out = [
        "// GENERATED by cpp26/tools/gen_tables.py from src/intrinsics.art,",
        "// src/semantics.art and src/front.art of the original compiler.",
        "// Do not edit by hand; re-run the generator after an Arturo bump.",
        "#pragma once",
        "struct BuiltinInfo { const char* name; int arity; const char* alias; bool infix; bool mutates; };",
        "inline constexpr BuiltinInfo kBuiltins[] = {",
    ]
    for name, arity, alias, infix, mut in rows:
        out.append(
            f'  {{"{esc(name)}", {arity}, "{esc(alias)}", '
            f'{"true" if infix else "false"}, {"true" if mut else "false"}}},'
        )
    out.append("};")
    for label, vals in (
        ("kPureIntrinsics", name_set(sem, "PURE_INTRINSICS")),
        ("kUnsupportedIntrinsics", name_set(sem, "UNSUPPORTED_INTRINSICS")),
        ("kShadowable", shadow),
    ):
        out.append(f"inline constexpr const char* {label}[] = {{")
        out += [f'  "{esc(v)}",' for v in vals]
        out.append("};")
    (ROOT / "cpp26/src/tables.inc").write_text("\n".join(out) + "\n")
    print(f"wrote cpp26/src/tables.inc ({len(rows)} intrinsics)")


if __name__ == "__main__":
    main()
