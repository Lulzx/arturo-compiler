// direct_c.hpp -- the direct C backend (tier 1): compact IR -> C that
// performs the computation itself.
//
// Where the C backend (emit_c.hpp) emits code that rebuilds the IR tree and
// hands it to the runtime interpreter, this backend lowers what it can
// prove to plain C: control flow becomes C control flow, definitions become
// frame bindings through the runtime ABI, known intrinsics become direct
// runtime calls, arithmetic on two integers becomes checked inline C with
// a generic fallback, and a call to a binding-stable user function becomes
// a direct C call. Anything it cannot prove -- attributes, mutating
// references, loops with action bodies, exotic nodes -- falls back per
// expression to runNode on the runtime-built IR for exactly that subtree,
// so the generic path is always available and always correct.
#pragma once

#include <string>
#include <unordered_map>
#include <unordered_set>
#include <vector>

#include "emit_c.hpp"
#include "ir.hpp"
#include "parser.hpp"  // tables.inc sets (pure/mutating/shadowable)

namespace artc {

class DirectEmitter {
  public:
    DirectEmitter(const air::Program& p, CEmitter& ce) : p_(p), ce_(ce) {
        for (const char* n : kShadowable) shadowable_.insert(n);
        analyze(p_.root);
        if (p_.nodes[p_.root].op == air::Op::Seq) {
            for (auto k : p_.nodes[p_.root].kids) {
                const auto& n = p_.nodes[k];
                if (n.op != air::Op::Define || n.name == air::kNone || n.kids.empty()) continue;
                const auto& v = p_.nodes[n.kids[0]];
                if (v.op != air::Op::Function) continue;
                const std::string& name = p_.str(n.name);
                if (defineCount_[name] == 1 && letCount_[name] == 0) {
                    std::string cname = "df_" + std::to_string(n.kids[0]);
                    stableByName_[name] = cname;
                    stableFuncs_.push_back({n.kids[0], cname});
                }
            }
        }
    }

    std::string run() {
        std::string out =
            "/* generated by arturoc (C++26, direct backend): computation is\n"
            " * native C; the runtime is crossed only through its public ABI. */\n"
            "#include \"runtime.h\"\n#include <stdint.h>\n#include <stdio.h>\n#include <string.h>\n\n"
            "static Env* g_top;\n"
            "static Value loadv(Env* e, const char* n){\n"
            "\tif (env_bound(e, n)) return env_get(e, n);\n"
            "\tif (rt_builtin_known(n)){ Value v; v.k = V_BUILTIN; v.u.s = (char*)n; return v; }\n"
            "\t{ char b[512]; snprintf(b, sizeof b, \"name error: identifier not found: %s\", n); rt_error(b); }\n"
            "\treturn v_null();\n}\n"
            "static Value loadv_cached(Env* e, const char* n, Env** cf, int* ci, Value** cv){\n"
            "\tif (*cf && *ci >= 0 && *ci < (*cf)->n && (*cf)->vals == *cv && !strcmp((*cf)->names[*ci], n)){\n"
            "\t\tfor (Env* f = e; f; f = f->parent) if (f == *cf) return (*cf)->vals[*ci];\n"
            "\t}\n"
            "\tfor (Env* f = e; f; f = f->parent)\n"
            "\t\tfor (int i = 0; i < f->n; ++i)\n"
            "\t\t\tif (!strcmp(f->names[i], n)){ *cf = f; *ci = i; *cv = f->vals; return f->vals[i]; }\n"
            "\tif (rt_builtin_known(n)){ Value v; v.k = V_BUILTIN; v.u.s = (char*)n; return v; }\n"
            "\t{ char b[512]; snprintf(b, sizeof b, \"name error: identifier not found: %s\", n); rt_error(b); }\n"
            "\treturn v_null();\n}\n"
            "static void define_cached(Env* e, const char* n, Value v, Env** cf, int* ci, Value** cv){\n"
            "\tif (*cf == e && *ci >= 0 && *ci < e->n && e->vals == *cv && !strcmp(e->names[*ci], n)){ e->vals[*ci] = v; return; }\n"
            "\trt_define_local(e, n, v);\n"
            "\tfor (int i = 0; i < e->n; ++i)\n"
            "\t\tif (!strcmp(e->names[i], n)){ *cf = e; *ci = i; *cv = e->vals; break; }\n}\n"
            "static Value call_builtin(Env* e, const char* n, Value* a, int cnt){\n"
            "\tValue out; if (rt_builtin(n, e, a, cnt, &out)) return out;\n"
            "\trt_error(\"unknown builtin\"); return v_null();\n}\n"
            "static Value add_fast(Env* e, Value a, Value b){\n"
            "\tif (a.k == V_INT && b.k == V_INT){ __int128 r = (__int128)a.u.i + b.u.i;\n"
            "\t\tif (r <= INT64_MAX && r >= INT64_MIN) return v_int((long)r); }\n"
            "\treturn call_builtin(e, \"add\", (Value[]){a, b}, 2);\n}\n"
            "static Value sub_fast(Env* e, Value a, Value b){\n"
            "\tif (a.k == V_INT && b.k == V_INT){ __int128 r = (__int128)a.u.i - b.u.i;\n"
            "\t\tif (r <= INT64_MAX && r >= INT64_MIN) return v_int((long)r); }\n"
            "\treturn call_builtin(e, \"sub\", (Value[]){a, b}, 2);\n}\n"
            "static Value mul_fast(Env* e, Value a, Value b){\n"
            "\tif (a.k == V_INT && b.k == V_INT){ __int128 r = (__int128)a.u.i * b.u.i;\n"
            "\t\tif (r <= INT64_MAX && r >= INT64_MIN) return v_int((long)r); }\n"
            "\treturn call_builtin(e, \"mul\", (Value[]){a, b}, 2);\n}\n\n";
        for (auto& f : stableFuncs_)
            out += "static Value " + f.second + "(Env* closure, Value* args, int n);\n";
        out += "\n";
        for (auto& f : stableFuncs_) out += functionDef(f.first, f.second);
        out += "int main(int argc, char** argv){\n\truntime_set_args(argc, argv);\n\truntime_set_source(" +
               quoteC(p_.sourcePath) + ");\n\tEnv* e = env_new(NULL);\n\tg_top = e;\n";
        Gen g{*this};
        g.inMain = true;
        if (p_.nodes[p_.root].op == air::Op::Seq) {
            for (auto k : p_.nodes[p_.root].kids) g.stmt(out, k, true);
        } else g.stmt(out, p_.root, true);
        out += "\treturn 0;\n}\n";
        return out;
    }

  private:
    const air::Program& p_;
    CEmitter& ce_;
    std::unordered_map<std::string, int> defineCount_, letCount_;
    std::unordered_map<std::string, std::string> stableByName_;
    std::vector<std::pair<std::uint32_t, std::string>> stableFuncs_;
    std::unordered_set<std::string> shadowable_, mutating_;

    void analyze(std::uint32_t id) {
        const auto& n = p_.nodes[id];
        if ((n.op == air::Op::Define || n.op == air::Op::Let) && n.name != air::kNone)
            (n.op == air::Op::Define ? defineCount_ : letCount_)[p_.str(n.name)]++;
        for (auto k : n.kids) analyze(k);
        for (auto& a : n.attrs) analyze(a.second);
    }
    bool isMutating(const std::string& name) const {
        // generated from the upstream PathLiteral declarations (tables.inc)
        for (const auto& b : kBuiltins)
            if (name == b.name) return b.mutates && name != "call" && name != "info";
        return false;
    }

    struct Gen {
        DirectEmitter& d;
        int tmp = 0;
        bool inMain = false;
        std::string fresh() { return "t" + std::to_string(tmp++); }

        void stmt(std::string& out, std::uint32_t id, bool) { (void)expr(out, id); }
        // append statements computing node `id` in env `e`; returns the C
        // variable holding the value
        std::string expr(std::string& out, std::uint32_t id) {
            const air::Program& p = d.p_;
            const auto& n = p.nodes[id];
            std::string v = fresh();
            auto fallback = [&]() {
                out += "\tValue " + v + " = runNode(e, " + d.ce_.expr(id) + ");\n";
                return v;
            };
            using O = air::Op;
            switch (n.op) {
                case O::Const:
                    out += "\tValue " + v + " = " + d.ce_.constExpr(p.consts[n.con]) + ";\n";
                    return v;
                case O::Load: {
                    std::string cid = std::to_string(id);
                    out += "\tstatic Env* lc_" + cid + "; static int li_" + cid +
                           " = -1; static Value* lv_" + cid + ";\n";
                    out += "\tValue " + v + " = loadv_cached(e, " + quoteC(p.str(n.name)) + ", &lc_" +
                           cid + ", &li_" + cid + ", &lv_" + cid + ");\n";
                    return v;
                }
                case O::Define: case O::Let: {
                    std::string x = expr(out, n.kids[0]);
                    if (n.op == O::Define) {
                        std::string cid = std::to_string(id);
                        out += "\tstatic Env* dc_" + cid + "; static int di_" + cid +
                               " = -1; static Value* dv_" + cid + ";\n";
                        out += "\tdefine_cached(e, " + quoteC(p.str(n.name)) + ", " + x + ", &dc_" +
                               cid + ", &di_" + cid + ", &dv_" + cid + ");\n";
                    } else {
                        out += "\trt_let(e, " + quoteC(p.str(n.name)) + ", " + x + ");\n";
                    }
                    out += "\tValue " + v + " = " + x + ";\n";
                    return v;
                }
                case O::Seq: {
                    out += "\tValue " + v + " = v_null();\n";
                    for (auto k : n.kids) out += "\t" + v + " = " + expr(out, k) + ";\n";
                    return v;
                }
                case O::Do:
                    // a literal block body is already a statement sequence;
                    // anything else may evaluate to a block value that the
                    // runtime must then execute as code -- the generic path
                    if (p.nodes[n.kids[0]].op == O::Seq) return expr(out, n.kids[0]);
                    return fallback();
                case O::If: {
                    std::string c = expr(out, n.kids[0]);
                    out += "\tValue " + v + " = v_null();\n\tif (v_truthy(" + c + ")){\n";
                    std::string y = expr(out, n.kids[1]);
                    out += "\t" + v + " = " + y + ";\n\t}";
                    if (n.kids.size() > 2) {
                        out += " else {\n";
                        std::string z = expr(out, n.kids[2]);
                        out += "\t" + v + " = " + z + ";\n\t}";
                    }
                    out += "\n";
                    return v;
                }
                case O::Unless: {
                    std::string c = expr(out, n.kids[0]);
                    out += "\tValue " + v + " = v_null();\n\tif (!v_truthy(" + c + ")){\n";
                    std::string y = expr(out, n.kids[1]);
                    out += "\t" + v + " = " + y + ";\n\t}\n";
                    return v;
                }
                case O::While: {
                    out += "\tValue " + v + " = v_null();\n\twhile (1){\n";
                    std::string c = expr(out, n.kids[0]);
                    out += "\tif (!v_truthy(" + c + ")) break;\n";
                    (void)expr(out, n.kids[1]);
                    out += "\t}\n";
                    return v;
                }
                case O::Until: {
                    out += "\tValue " + v + " = v_null();\n\twhile (1){\n";
                    (void)expr(out, n.kids[0]);
                    std::string c = expr(out, n.kids[1]);
                    out += "\tif (v_truthy(" + c + ")) break;\n\t}\n";
                    return v;
                }
                case O::Return: {
                    if (inMain) {
                        out += "\treturn 0;\n";
                    } else {
                        std::string x = n.kids.empty() ? "v_null()" : expr(out, n.kids[0]);
                        out += "\treturn " + x + ";\n";
                    }
                    out += "\tValue " + v + " = v_null();\n";
                    return v;
                }
                case O::Break:
                    out += "\tbreak;\n\tValue " + v + " = v_null();\n";
                    return v;
                case O::Continue:
                    out += "\tcontinue;\n\tValue " + v + " = v_null();\n";
                    return v;
                case O::Call: return call(out, id, v);
                default: return fallback();
            }
        }
        std::string call(std::string& out, std::uint32_t id, const std::string& v) {
            const air::Program& p = d.p_;
            const auto& n = p.nodes[id];
            if (!n.attrs.empty()) {
                out += "\tValue " + v + " = runNode(e, " + d.ce_.expr(id) + ");\n";
                return v;
            }
            const auto& fn = p.nodes[n.kids[0]];
            // a mutating intrinsic only mutates through a reference first
            // argument (a passthrough node); decide before evaluating any
            // argument, so a fallback never re-runs computed subexpressions
            if (fn.op == air::Op::Intrinsic && fn.name != air::kNone && n.kids.size() > 1 &&
                d.isMutating(p.str(fn.name)) && p.nodes[n.kids[1]].op == air::Op::Passthrough) {
                out += "\tValue " + v + " = runNode(e, " + d.ce_.expr(id) + ");\n";
                return v;
            }
            std::vector<std::string> args;
            for (std::size_t i = 1; i < n.kids.size(); ++i) args.push_back(expr(out, n.kids[i]));
            auto argArray = [&]() {
                if (args.empty()) return std::string("NULL");
                std::string s = "(Value[]){";
                for (std::size_t i = 0; i < args.size(); ++i) s += (i ? ", " : "") + args[i];
                return s + "}";
            };
            if (fn.op == air::Op::Intrinsic && fn.name != air::kNone) {
                const std::string name = p.str(fn.name);
                if (args.size() == 2 && (name == "add" || name == "sub" || name == "mul")) {
                    out += "\tValue " + v + " = " + name + "_fast(e, " + args[0] + ", " + args[1] + ");\n";
                    return v;
                }
                std::string cnt = std::to_string(args.size());
                if (d.shadowable_.count(name)) {
                    out += "\tValue " + v + ";\n\tif (env_bound(e, " + quoteC(name) +
                           ")) " + v + " = rt_apply(e, env_get(e, " + quoteC(name) + "), " + argArray() +
                           ", " + cnt + ");\n\telse " + v + " = call_builtin(e, " + quoteC(name) + ", " +
                           argArray() + ", " + cnt + ");\n";
                } else {
                    out += "\tValue " + v + " = call_builtin(e, " + quoteC(name) + ", " + argArray() +
                           ", " + cnt + ");\n";
                }
                return v;
            }
            if (fn.op == air::Op::Load && fn.name != air::kNone) {
                auto it = d.stableByName_.find(p.str(fn.name));
                if (it != d.stableByName_.end()) {
                    out += "\tValue " + v + " = env_bound(g_top, " + quoteC(p.str(fn.name)) + ") ? " +
                           it->second + "(g_top, " + argArray() + ", " +
                           std::to_string(args.size()) + ") : loadv(e, " + quoteC(p.str(fn.name)) + ");\n";
                    return v;
                }
            }
            std::string fv = expr(out, n.kids[0]);
            out += "\tValue " + v + " = rt_apply(e, " + fv + ", " + argArray() + ", " +
                   std::to_string(args.size()) + ");\n";
            return v;
        }
    };

    std::string functionDef(std::uint32_t funcId, const std::string& cname) {
        const auto& fn = p_.nodes[funcId];
        const auto& params = p_.nodes[fn.kids[0]];
        std::string out = "static Value " + cname + "(Env* closure, Value* args, int n){\n"
                          "\tEnv* e = env_new(closure);\n";
        for (std::size_t i = 0; i < params.names.size(); ++i) {
            out += "\trt_define_local(e, " + quoteC(p_.str(params.names[i])) + ", n > " +
                   std::to_string(i) + " ? args[" + std::to_string(i) + "] : v_null());\n";
        }
        out += "\tValue result = v_null();\n";
        Gen g{*this};
        for (std::size_t i = 1; i < fn.kids.size(); ++i) {
            std::string body;
            std::string v = g.expr(body, fn.kids[i]);
            out += body + "\tresult = " + v + ";\n";
        }
        out += "\treturn result;\n}\n\n";
        return out;
    }
};

}  // namespace artc
