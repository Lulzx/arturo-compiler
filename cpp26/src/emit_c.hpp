// emit_c.hpp -- the C backend: compact IR -> C source built on the original
// runtime's IR builders, linked against runtime.a. This is the same shape as
// the original cbackend.art output, but generated from the compact IR after
// optimization instead of from Arturo dictionary IR before it.
#pragma once

#include <cstdio>
#include <string>
#include <vector>

#include "ir.hpp"

namespace artc {

inline std::string escapeC(const std::string& s) {
    std::string out;
    for (unsigned char c : s) {
        switch (c) {
            case '\\': out += "\\\\"; break;
            case '"': out += "\\\""; break;
            case '\n': out += "\\n"; break;
            case '\r': out += "\\r"; break;
            case '\t': out += "\\t"; break;
            default:
                if (c < 0x20) {
                    char buf[8];
                    std::snprintf(buf, sizeof(buf), "\\%03o", c);
                    out += buf;
                } else out += static_cast<char>(c);
        }
    }
    return out;
}
inline std::string quoteC(const std::string& s) { return "\"" + escapeC(s) + "\""; }

class CEmitter {
  public:
    explicit CEmitter(const air::Program& p) : p_(p) {}

    // one IR node as a runtime-builder C expression (used by the direct
    // backend for the subtrees it does not lower itself)
    std::string expr(std::uint32_t id) { return node(id); }
    std::string constExpr(const air::Const& c) { return value(c); }

    std::string run() {
        std::string out =
            "/* generated by arturoc (C++26) from optimized compact IR; links runtime.a */\n"
            "#include \"runtime.h\"\n#include <stdlib.h>\n\n"
            "static Value block_of(Value* vals, int n){\n"
            "\tValue** p = (Value**)runtime_alloc(sizeof(Value*) * (size_t)(n > 0 ? n : 1));\n"
            "\tfor (int i = 0; i < n; ++i){ Value* c = (Value*)runtime_alloc(sizeof(Value)); *c = vals[i]; p[i] = c; }\n"
            "\treturn v_block(p, n);\n}\n\n";
        const auto& root = p_.nodes[p_.root];
        std::vector<std::uint32_t> stmts = root.op == air::Op::Seq ? root.kids
                                         : std::vector<std::uint32_t>{p_.root};
        std::string calls;
        for (std::size_t i = 0; i < stmts.size(); ++i) {
            out += "static IR* stmt_" + std::to_string(i) + "(void){ return " + node(stmts[i]) + "; }\n";
            calls += (i ? ",\n\t\t" : "\t\t") + ("stmt_" + std::to_string(i) + "()");
        }
        out += "\nint main(int argc, char** argv){\n\truntime_set_args(argc, argv);\n\truntime_set_source(" +
               quoteC(p_.sourcePath) + ");\n\tEnv* e = env_new(NULL);\n\tIR* seq[] = {\n" + calls +
               "\n\t};\n\trunSeq(e, seq, " + std::to_string(stmts.size()) + ");\n\treturn 0;\n}\n";
        return out;
    }

  private:
    const air::Program& p_;

    std::string value(const air::Const& c) {
        using K = air::CKind;
        switch (c.kind) {
            case K::Null: return "v_null()";
            case K::Int: return "v_int(" + std::to_string(c.i) + "LL)";
            case K::BigInt: return "v_bigint_text(" + quoteC(c.s) + ")";
            case K::Float: {
                char buf[64];
                std::snprintf(buf, sizeof(buf), "%.17g", c.f);
                return "v_float_text(" + quoteC(buf) + ")";
            }
            case K::Str: return "v_str(" + quoteC(c.s) + ")";
            case K::Char: return "v_char_text(" + quoteC(c.s) + ")";
            case K::Bool: return c.b ? "v_bool(1)" : "v_bool(0)";
            case K::Word: return "v_token(V_WORD, " + quoteC(c.s) + ")";
            case K::Literal: return "v_token(V_LITERAL, " + quoteC(c.s) + ")";
            case K::Symbol: return "v_token(V_SYMBOL, " + quoteC(c.s) + ")";
            case K::SymbolLiteral: return "v_token(V_SYMBOLLITERAL, " + quoteC(c.s) + ")";
            case K::Type: return "v_token(V_TYPE, " + quoteC(":" + c.s) + ")";
            case K::Label: return "v_str(" + quoteC("@LBL:" + c.s) + ")";
            case K::Quantity: {
                char buf[64];
                std::snprintf(buf, sizeof(buf), "%.17g", c.f);
                return c.b ? "v_quantity_int(" + std::to_string(c.i) + "LL, " + quoteC(c.s) + ")"
                           : "v_quantity(" + std::string(buf) + ", " + quoteC(c.s) + ")";
            }
            case K::Unit: return "v_unit(" + quoteC(c.s) + ")";
            case K::Version: return "v_version(" + quoteC(c.s) + ")";
            case K::Color: return "v_color_hex(" + quoteC(c.s) + ")";
            case K::Rational: {
                auto slash = c.s.find('/');
                return "v_rational(" + c.s.substr(0, slash) + "LL, " +
                       (slash == std::string::npos ? std::string("1") : c.s.substr(slash + 1)) + "LL)";
            }
            case K::Regex: return "v_token(V_REGEX, " + quoteC(c.s) + ")";
            case K::Attribute: return "v_token(V_ATTRIBUTE, " + quoteC(c.s) + ")";
            case K::AttributeLabel: return "v_token(V_ATTRIBUTELABEL, " + quoteC(c.s) + ")";
            case K::PathLiteral: {
                std::string segs;
                for (std::size_t i = 0; i < c.items.size(); ++i)
                    segs += (i ? ", " : "") + quoteC(c.items[i].s);
                return "v_path((char*[]){" + segs + "}, " + std::to_string(c.items.size()) + ")";
            }
            case K::Block: case K::Inline: {
                if (c.items.empty()) return "block_of(NULL, 0)";
                std::string vals;
                for (std::size_t i = 0; i < c.items.size(); ++i)
                    vals += (i ? ", " : "") + value(c.items[i]);
                return "block_of((Value[]){" + vals + "}, " + std::to_string(c.items.size()) + ")";
            }
        }
        return "v_null()";
    }
    std::string nodeList(const std::vector<std::uint32_t>& kids, std::size_t from = 0) {
        std::string out;
        for (std::size_t i = from; i < kids.size(); ++i)
            out += (i > from ? ", " : "") + node(kids[i]);
        return out;
    }
    std::string paramsBlock(const air::Node& params, bool asLoads) {
        if (params.names.empty()) return "ir_block((IR*[]){0}, 0)";
        std::string items;
        for (std::size_t i = 0; i < params.names.size(); ++i) {
            const std::string& nm = p_.str(params.names[i]);
            items += (i ? ", " : "") + (asLoads ? "ir_load(" + quoteC(nm) + ")"
                                                : "ir_const(v_str(" + quoteC(nm) + "))");
        }
        return "ir_block((IR*[]){" + items + "}, " + std::to_string(params.names.size()) + ")";
    }
    static const char* runtimeName(air::Op op) {
        switch (op) {
            case air::Op::If: return "if";
            case air::Op::Unless: return "unless";
            case air::Op::Switch: return "switch";
            case air::Op::When: return "when";
            case air::Op::Using: return "using";
            case air::Op::Try: return "try";
            case air::Op::ThrowsQ: return "throws?";
            case air::Op::Ensure: return "ensure";
            case air::Op::Do: return "do";
            case air::Op::Return: return "return";
            case air::Op::While: return "while";
            case air::Op::Until: return "until";
            case air::Op::Dictionary: return "dictionary";
            case air::Op::Is: return "is";
            case air::Op::Break: return "break";
            case air::Op::Continue: return "continue";
            default: return "passthrough";
        }
    }
    std::string withAttrs(const std::string& base, const air::Node& n, bool isCall) {
        if (n.attrs.empty()) return base;
        std::string names, vals;
        for (std::size_t i = 0; i < n.attrs.size(); ++i) {
            names += (i ? ", " : "") + quoteC(p_.str(n.attrs[i].first));
            vals += (i ? ", " : "") + node(n.attrs[i].second);
        }
        std::string cnt = std::to_string(n.attrs.size());
        if (isCall) return base;  // call sites use ir_call_attrs directly in node()
        return "ir_attrs(" + base + ", (const char*[]){" + names + "}, (IR*[]){" + vals + "}, " + cnt + ")";
    }
    std::string node(std::uint32_t id) {
        std::string inner = nodeImpl(id);
        const air::Node& n = p_.nodes[id];
        if (n.line > 0) return "ir_line(" + inner + ", " + std::to_string(n.line) + ")";
        return inner;
    }
    std::string nodeImpl(std::uint32_t id) {
        const air::Node& n = p_.nodes[id];
        using O = air::Op;
        switch (n.op) {
            case O::Seq:
                return "ir_seq((IR*[]){" + nodeList(n.kids) + "}, " + std::to_string(n.kids.size()) + ")";
            case O::Const: return "ir_const(" + value(p_.consts[n.con]) + ")";
            case O::Passthrough: return "ir_passthrough(" + value(p_.consts[n.con]) + ")";
            case O::Load: return "ir_load(" + quoteC(p_.str(n.name)) + ")";
            case O::Intrinsic: return "ir_word(" + quoteC(p_.str(n.name)) + ")";
            case O::Define: return "ir_define(" + quoteC(p_.str(n.name)) + ", " + node(n.kids[0]) + ")";
            case O::Let: return "ir_let(" + quoteC(p_.str(n.name)) + ", " + node(n.kids[0]) + ")";
            case O::Call: {
                const auto& fn = p_.nodes[n.kids[0]];
                std::string fnc = fn.op == O::Intrinsic
                                      ? "ir_intrinsic(" + quoteC(p_.str(fn.name)) + ")"
                                      : node(n.kids[0]);
                std::string args = nodeList(n.kids, 1);
                std::string cnt = std::to_string(n.kids.size() - 1);
                if (!n.attrs.empty()) {
                    std::string names, vals;
                    for (std::size_t i = 0; i < n.attrs.size(); ++i) {
                        names += (i ? ", " : "") + quoteC(p_.str(n.attrs[i].first));
                        vals += (i ? ", " : "") + node(n.attrs[i].second);
                    }
                    return "ir_call_attrs(" + fnc + ", (IR*[]){" + args + "}, " + cnt +
                           ", (const char*[]){" + names + "}, (IR*[]){" + vals + "}, " +
                           std::to_string(n.attrs.size()) + ")";
                }
                return "ir_call(" + fnc + ", (IR*[]){" + args + "}, " + cnt + ")";
            }
            case O::Function: {
                std::string body = nodeList(n.kids, 1);
                std::string base = "ir_fn(" + paramsBlock(p_.nodes[n.kids[0]], true) + ", (IR*[]){" + body +
                                   "}, " + std::to_string(n.kids.size() - 1) + ")";
                return withAttrs(base, n, false);
            }
            case O::Method: {
                std::string all = paramsBlock(p_.nodes[n.kids[0]], true);
                if (n.kids.size() > 1) all += ", " + nodeList(n.kids, 1);
                return "ir_op(\"method\", (IR*[]){" + all + "}, " + std::to_string(n.kids.size()) + ")";
            }
            case O::Params: return paramsBlock(n, true);
            case O::Block:
                return "ir_block((IR*[]){" + nodeList(n.kids) + "}, " + std::to_string(n.kids.size()) + ")";
            case O::Higher: {
                std::string base = "ir_higher(" + quoteC(p_.str(n.name)) + ", " + node(n.kids[0]) + ", " +
                                   paramsBlock(p_.nodes[n.kids[1]], false) + ", " + node(n.kids[2]);
                if (n.attrs.empty()) return base + ", NULL, NULL, 0)";
                std::string names, vals;
                for (std::size_t i = 0; i < n.attrs.size(); ++i) {
                    names += (i ? ", " : "") + quoteC(p_.str(n.attrs[i].first));
                    vals += (i ? ", " : "") + node(n.attrs[i].second);
                }
                return base + ", (const char*[]){" + names + "}, (IR*[]){" + vals + "}, " +
                       std::to_string(n.attrs.size()) + ")";
            }
            case O::Loop: {
                std::string base = "ir_op(\"loop\", (IR*[]){" + node(n.kids[0]) + ", " +
                                   paramsBlock(p_.nodes[n.kids[1]], false) + ", " + node(n.kids[2]) + "}, 3)";
                return withAttrs(base, n, false);
            }
            case O::Constructor:
                return "ir_op(\"constructor\", (IR*[]){" + paramsBlock(p_.nodes[n.kids[0]], false) + "}, 1)";
            case O::Range: {
                std::string base = "ir_op(\"range\", (IR*[]){" + node(n.kids[0]) + ", " + node(n.kids[1]) + "}, 2)";
                return withAttrs(base, n, false);
            }
            default: {
                std::string base = "ir_op(" + quoteC(runtimeName(n.op)) + ", (IR*[]){" + nodeList(n.kids) +
                                   "}, " + std::to_string(n.kids.size()) + ")";
                return withAttrs(base, n, false);
            }
        }
    }
};

}  // namespace artc
